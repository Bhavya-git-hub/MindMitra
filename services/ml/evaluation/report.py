"""Render the evaluation reports as one Markdown page (``evaluation/reports/REPORT.md``)."""

from collections.abc import Sequence
from typing import Any

_HEADER = """# Wellness indicator models: evaluation report

> **Synthetic data only.** Every number below comes from data generated by
> `data/synthetic.py` and `data/text_corpus.py`. It shows that the pipeline works and how the
> algorithms compare on data of this shape. It says **nothing** about accuracy with real
> students, and none of these models is a clinical or diagnostic tool. See the model cards in
> `model_cards/` for limitations.

"""


def _cell(stats: dict[str, Any], key: str) -> str:
    s = stats.get(key)
    return f"{s['mean']:.3f} ± {s['sd']:.3f}" if s else "n/a"


def _matrix(m: Sequence[Sequence[int]], labels: Sequence[str]) -> list[str]:
    head = "| actual \\ predicted | " + " | ".join(labels) + " |"
    rule = "|---|" + "---|" * len(labels)
    rows = [f"| {labels[i]} | " + " | ".join(str(v) for v in row) + " |" for i, row in enumerate(m)]
    return [head, rule, *rows]


def _section(r: dict[str, Any]) -> list[str]:
    t = r["test"]
    lines = [f"## {r['title']} (`{r['indicator']}`)", ""]
    lines.append(
        f"Selected **{r['selected']}** by {r['selection_metric']} "
        f"({r['cv_folds']}-fold). Train {r['n_train']}, test {r['n_test']}."
    )
    lines += ["", "Cross-validation (mean ± sd across folds):", ""]
    lines.append("| model | accuracy | precision | recall | F1 | ROC-AUC |")
    lines.append("|---|---|---|---|---|---|")
    for name, stats in r["candidates"].items():
        mark = " (selected)" if name == r["selected"] else ""
        cells = " | ".join(_cell(stats, k) for k in ("accuracy", "precision", "recall", "f1"))
        lines.append(f"| {name}{mark} | {cells} | {_cell(stats, 'roc_auc')} |")
    seen = {n: s["seen_patterns_f1"] for n, s in r["candidates"].items() if "seen_patterns_f1" in s}
    if seen:
        parts = ", ".join(f"{n} {s['mean']:.3f}" for n, s in seen.items())
        lines += [
            "",
            "The table above holds out whole sentence patterns. On a plain random split "
            f"(patterns already seen), macro F1 is: {parts}. The gap is how much depends on "
            "memorised sentence shapes.",
        ]
    lines += ["", "Held-out test set, selected model:", ""]
    if r["kind"] == "binary":
        lines.append(
            f"Threshold for elevated {t['threshold']} (moderate from "
            f"{r['thresholds'].get('moderate')}). "
            f"Accuracy {t['accuracy']}, precision {t['precision']}, recall {t['recall']}, "
            f"F1 {t['f1']}, ROC-AUC {t['roc_auc']}, average precision "
            f"{t['average_precision']}, Brier {t['brier']}. Prevalence {t['prevalence']}; "
            f"recall at the moderate cut-off {t.get('recall_at_moderate')}."
        )
        shares = t.get("band_shares")
        if shares:
            lines.append(
                f"Share of test students per band: low {shares['low']}, moderate "
                f"{shares['moderate']}, elevated {shares['elevated']}."
            )
    else:
        lines.append(
            f"Accuracy {t['accuracy']}, macro precision {t['precision']}, macro recall "
            f"{t['recall']}, macro F1 {t['f1']}, ROC-AUC (one-vs-rest) {t['roc_auc']}."
        )
    lines += ["", *_matrix(t["confusion_matrix"], t["confusion_matrix_labels"]), ""]
    lines.append("Baseline: " + ", ".join(f"{k} {v}" for k, v in r["baseline"].items()) + ".")
    if r.get("top_features"):
        top = ", ".join(f"`{f['feature']}` ({f['importance']})" for f in r["top_features"][:5])
        lines += ["", f"Most influential features (permutation importance on test): {top}."]
    if "hard_case_accuracy" in r:
        lines += [
            "",
            f"Accuracy on {r['hard_cases']} hand-written hard cases (mixed feelings, sarcasm): "
            f"{r['hard_case_accuracy']}.",
        ]
    others = r.get("other_models_on_test") or {}
    if others:
        lines += ["", "Other models on the same held-out test set:", ""]
        lines.append("| model | accuracy | macro F1 | ROC-AUC | hard cases | note |")
        lines.append("|---|---|---|---|---|---|")
        for name, o in others.items():
            if "skipped" in o:
                lines.append(f"| {name} | - | - | - | - | skipped: {o['skipped']} |")
                continue
            ot = o["test"]
            note = o.get("note", "")
            if "parameters" in o:
                note = f"{note} {o['parameters']:,} parameters, {o['train_seconds']} s".strip()
            lines.append(
                f"| {name} | {ot['accuracy']} | {ot['f1']} | {ot['roc_auc']} | "
                f"{o['hard_case_accuracy']} | {note} |"
            )
    return [*lines, ""]


def render(reports: Sequence[dict[str, Any]], *, run: dict[str, Any]) -> str:
    lines = [_HEADER.rstrip(), ""]
    lines.append(
        f"Run: {run['trained_at']}, cohort `{run['generator']}` seed {run['seed']} "
        f"({run['students']} students, {run['excluded_low_data']} excluded for fewer than "
        f"{run['min_checkin_days']} check-in days), notes `{run['corpus']}`. Libraries: "
        + ", ".join(f"{k} {v}" for k, v in run["libraries"].items())
        + "."
    )
    lines.append("")
    for r in reports:
        lines += _section(r)
    return "\n".join(lines).rstrip() + "\n"
